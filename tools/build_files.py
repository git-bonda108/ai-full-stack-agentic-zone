def main() -> None:
    bundle, missing = {}, []
    for rel in FILES:
        path = ROOT / rel
        if path.exists():
            bundle[rel] = path.read_text(encoding="utf-8")
        else:
            missing.append(rel)
    out = ROOT / "content" / "files.js"
    out.write_text(
        "/* GENERATED by tools/build_files.py - do not edit by hand. */\n"
        f"Zone.set(\"files\", {json.dumps(bundle, indent=1, ensure_ascii=False)});\n",
        encoding="utf-8",
    )
    print(f"bundled {len(bundle)} files into {out.relative_to(ROOT)}")
    if missing:
        print("missing (skipped):", *missing, sep="\n  ")


if __name__ == "__main__":
    main()
